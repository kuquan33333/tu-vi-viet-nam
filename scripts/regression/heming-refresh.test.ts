import assert from 'node:assert/strict';
import {formAt,invoke} from './helpers/heming-callback';
import {compareCharts} from '../../lib/ziwei/client-reading';
const a=formAt('1990','A'),b=formAt('1992','B');
const first=invoke(a,b),second=invoke({...a,year:'1991'},b);
assert.ok(first.a&&first.b&&second.a&&second.b);
assert.equal(first.a.birthInfo.year,1990);
assert.equal(second.a.birthInfo.year,1991,'Edited birth input must replace previous chart');
assert.equal(second.b.birthInfo.name,'B');
assert.equal(first.networkCalls+second.networkCalls,0);
assert.equal(compareCharts(second.a,second.b).length,12);
assert.notDeepEqual(first.a.palaces,second.a.palaces);
console.log('Hợp bàn: thay đổi dữ liệu tạo lại lá số, không gửi dữ liệu sinh ra mạng.');
